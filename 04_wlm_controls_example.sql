-- Restrict a shared account: trusted context + WLM limits.
-- STOP EXECUTION cancels running statements: agree on limits with the business first.
-- Replace APP_SHARED_USER, the IP address and the thresholds.
----------------------------------------------------------------------------------

-- 1. Remove implicit CONNECT for everyone, grant it explicitly
REVOKE CONNECT ON DATABASE FROM PUBLIC;
CREATE ROLE APP_CONNECT;
GRANT CONNECT ON DATABASE TO ROLE APP_CONNECT;
GRANT ROLE APP_CONNECT TO USER APP_SHARED_USER;

-- 2. Bind the account to an approved source host
CREATE ROLE APP_ROLE;
CREATE TRUSTED CONTEXT CTX_SHARED_USER
  BASED UPON CONNECTION USING SYSTEM AUTHID APP_SHARED_USER
  ATTRIBUTES (ADDRESS '10.0.0.25')
  DEFAULT ROLE APP_ROLE
  ENABLE;

-- 3. WLM: isolate the account and cap its activity
CREATE SERVICE CLASS SC_SHARED_USER;
CREATE WORKLOAD WL_SHARED_USER SESSION_USER ('APP_SHARED_USER') SERVICE CLASS SC_SHARED_USER;
GRANT USAGE ON WORKLOAD WL_SHARED_USER TO PUBLIC;

CREATE THRESHOLD TH_SHARED_CONC FOR SERVICE CLASS SC_SHARED_USER ACTIVITIES
  ENFORCEMENT DATABASE
  WHEN CONCURRENTDBCOORDACTIVITIES > 5 STOP EXECUTION;

CREATE THRESHOLD TH_SHARED_TIME FOR SERVICE CLASS SC_SHARED_USER ACTIVITIES
  ENFORCEMENT DATABASE
  WHEN ACTIVITYTOTALTIME > 10 MINUTES STOP EXECUTION;

-- Thresholds are created DISABLED
ALTER THRESHOLD TH_SHARED_CONC ENABLE;
ALTER THRESHOLD TH_SHARED_TIME ENABLE;

